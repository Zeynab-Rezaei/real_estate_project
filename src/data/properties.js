export const propertyCities = [...new Set(properties.map((p) => p.location.city))].sort();

export function getProperty(slug) {
  return properties.find((property) => property.slug === slug);
}

export function getSimilarProperties(property, limit = 3) {
  return properties
    .filter((candidate) => candidate.slug !== property.slug)
    .sort((a, b) => {
      const score = (p) =>
        (p.type === property.type ? 2 : 0) +
        (p.location.region === property.location.region ? 1 : 0);
      return score(b) - score(a) || Math.abs(a.price - property.price) - Math.abs(b.price - property.price);
    })
    .slice(0, limit);
}
